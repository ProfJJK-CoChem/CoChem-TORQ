class BenchmarkDesign(ScientificContract):
    schema_version: Literal["cochem.torq.frozen-benchmark-design/1"] = (
        "cochem.torq.frozen-benchmark-design/1"
    )
    benchmark_id: Name
    proposal_sha256: Sha256
    reference_manifest_sha256: Sha256
    curation_sha256: Sha256
    recipe_sha256: Sha256
    source_code_sha256: Sha256
    source_commit: Annotated[str, Field(pattern=r"^[0-9a-f]{40}$")]
    selected_references: tuple[SelectedReference, ...] = Field(min_length=1)
    targets: tuple[AcceptedTarget, ...] = Field(min_length=1)
    accepted_by: Name
    accepted_at: datetime
    acceptance_record_sha256: Sha256
    protocol: Name
    exchangeability_assessment: Literal["not_established", "externally_supported"]
    exchangeability_review: Name
    nominal_coverage: StrictFloat = Field(gt=0, lt=1)

    @model_validator(mode="after")
    def fixed_design_without_leakage(self) -> Self:
        _aware(self.accepted_at)
        if len({r.reference_id for r in self.selected_references}) != len(
            self.selected_references
        ):
            raise ValueError("Selected references must have unique IDs.")
        families: dict[str, Partition] = {}
        parents: dict[str, tuple[str, Partition]] = {}
        sources: dict[str, Partition] = {}
        for ref in self.selected_references:
            if (
                families.setdefault(ref.identity.family_id, ref.partition)
                != ref.partition
            ):
                raise ValueError("A chemical family cannot cross benchmark partitions.")
            if parents.setdefault(
                ref.identity.parent_id, (ref.identity.family_id, ref.partition)
            ) != (ref.identity.family_id, ref.partition):
                raise ValueError(
                    "Related parent states cannot cross family partitions."
                )
            if sources.setdefault(ref.source_sha256, ref.partition) != ref.partition:
                raise ValueError(
                    "Shared reference source artifacts cannot cross partitions."
                )
        targets = {target.observable: target for target in self.targets}
        if len(targets) != len(self.targets):
            raise ValueError("Each observable requires exactly one fixed target.")
        if set(targets) != {r.identity.observable for r in self.selected_references}:
            raise ValueError(
                "Every selected observable needs an accepted numerical target."
            )
        if any(
            targets[r.identity.observable].unit != r.identity.unit
            for r in self.selected_references
        ):
            raise ValueError("Target and reference observable units differ.")
        if not {"calibration", "held_out"}.issubset(
            {r.partition for r in self.selected_references}
        ):
            raise ValueError(
                "Independent calibration and held-out partitions are required."
            )
        return self


def _safe_parent(path: Path) -> None:
    for component in (path, *path.parents):
        if component.is_symlink():
            raise ValueError("Benchmark artifacts cannot traverse symlinks.")
    path.mkdir(parents=True, exist_ok=True, mode=0o700)


def _write_once(path: str | Path, payload: Mapping[str, Any]) -> str:
    """Fsync a private file, then atomic no-overwrite hard-link publication."""
    target = Path(path).absolute()
    _safe_parent(target.parent)
    raw = canonical_json(payload) + b"\n"
    descriptor, temporary = tempfile.mkstemp(
        prefix=".torq-benchmark-", dir=target.parent
    )
    temporary_path = Path(temporary)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(raw)
            stream.flush()
            os.fsync(stream.fileno())
        os.link(temporary_path, target, follow_symlinks=False)
        directory = os.open(target.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        temporary_path.unlink(missing_ok=True)
    return sha256(raw).hexdigest()


def freeze_benchmark(
    design: BenchmarkDesign, acceptance_record: bytes, destination: str | Path
) -> dict[str, Any]:
    """Freeze supplied accepted metadata without opening held-out values.

    This receipt fixes inputs and targets; it cannot certify the human acceptance
    or reference review. Amendments require a new destination/design and require
    inspected held-out subjects to be reclassified as development.
    """
    if sha256(acceptance_record).hexdigest() != design.acceptance_record_sha256:
        raise ValueError("Accepted design requires its actual acceptance-record bytes.")
    accepted = _decode(acceptance_record)
    if (
        not isinstance(accepted, dict)
        or accepted.get("design_sha256")
        != digest(design.model_dump(mode="json", exclude={"acceptance_record_sha256"}))
        or accepted.get("accepted_by") != design.accepted_by
    ):
        raise ValueError(
            "Acceptance record does not bind this exact design and reviewer."
        )
    now = datetime.now(timezone.utc)
    if design.accepted_at > now:
        raise ValueError("A future acceptance cannot freeze a benchmark.")
    payload = {
        "schema_version": "cochem.torq.benchmark-freeze/1",
        "design": design.model_dump(mode="json"),
        "design_sha256": digest(design.model_dump(mode="json")),
        "frozen_at": now.isoformat(),
        "acceptance_record": accepted,
        "acceptance_record_utf8": acceptance_record.decode("utf-8"),
        "experimental_accuracy_established": False,
    }
    artifact_sha256 = _write_once(destination, payload)
    return {"freeze_sha256": artifact_sha256, "design_sha256": payload["design_sha256"]}


def _read_frozen(
    path: str | Path, expected_sha256: str
) -> tuple[BenchmarkDesign, datetime]:
    file = Path(path).absolute()
    for component in (file, *file.parents):
        if component.is_symlink():
            raise ValueError("Benchmark artifacts cannot traverse symlinks.")
    raw = file.read_bytes()
    if sha256(raw).hexdigest() != expected_sha256:
        raise ValueError("Frozen benchmark differs from independently retained digest.")
    payload = _decode(raw)
    if payload.get("schema_version") != "cochem.torq.benchmark-freeze/1":
        raise ValueError("Unsupported benchmark-freeze schema.")
    design = BenchmarkDesign.model_validate(payload["design"])
    if digest(design.model_dump(mode="json")) != payload.get("design_sha256"):
        raise ValueError("Frozen design digest mismatch.")
    acceptance_bytes = payload["acceptance_record_utf8"].encode("utf-8")
    accepted = _decode(acceptance_bytes)
    if (
        sha256(acceptance_bytes).hexdigest() != design.acceptance_record_sha256
        or accepted != payload["acceptance_record"]
        or accepted.get("accepted_by") != design.accepted_by
        or accepted.get("design_sha256")
        != digest(design.model_dump(mode="json", exclude={"acceptance_record_sha256"}))
    ):
        raise ValueError("Frozen acceptance record does not bind this design.")
    frozen_at = _aware(datetime.fromisoformat(payload["frozen_at"]))
    if frozen_at < design.accepted_at or frozen_at > datetime.now(timezone.utc):
        raise ValueError("Freeze precedes design acceptance.")
    return design, frozen_at


def import_publication_prediction(
    bundle: str | Path, *, expected_manifest_sha256: str, identity: ObservableIdentity
) -> dict[str, Any]:
    """Extract implemented scalar observables from unchanged real native evidence.

    Chemical labels in source_provenance['benchmark_identity'] are declarations
    requiring curator review; isotope, charge and spin are checked against the
    actual request. Unsupported/unavailable stages produce an explicit absence.
    """
    manifest = verify_publication_bundle(
        bundle, expected_manifest_sha256=expected_manifest_sha256
    )
    root = Path(bundle)
    request = read_json(root / "shard/request.json")
    result = read_json(root / "shard/result.json")
    molecule = request["molecule"]
    isotopes = tuple(molecule.get("isotopes") or ())
    if None in isotopes or not isotopes:
        isotopes = tuple(
            r["mass_number"] for r in result.get("resolved_isotopes") or ()
        )
    if (
        tuple(molecule["symbols"]) != identity.symbols
        or isotopes != identity.isotope_numbers
        or molecule["charge"] != identity.charge
        or molecule["multiplicity"] != identity.multiplicity
    ):
        raise ValueError(
            "Prediction molecule/state/isotopes differ from curated identity."
        )
    labels = identity.model_dump(
        mode="json",
        include={
            "parent_id",
            "family_id",
            "conformer",
            "electronic_state",
            "vibrational_state",
            "tunneling_state",
            "hamiltonian_convention",
        },
    )
    if request.get("source_provenance", {}).get("benchmark_identity") != labels:
        raise ValueError("Benchmark labels must be sealed in the original request.")
    stages = {
        "electronic_energy": "electronic_structure",
        "equilibrium_rotational_constant": "equilibrium_constants",
        "ground_state_rotational_constant": "ground_state_constants",
        "rotational_transition": "identification_catalog",
        "relative_line_intensity": "identification_catalog",
    }
    stage = result["stages"][stages[identity.observable]]
    value: float | None = None
    reason = stage.get("reason")
    if stage["status"] == "available":
        if not read_json(root / "publication.json")["native_engine_evidence"]:
            raise ValueError(
                "Available prediction requires genuine retained native evidence."
            )
        if identity.observable == "electronic_energy":
            if identity.component != "total_electronic_energy":
                raise ValueError(
                    "Only the explicitly named total electronic energy is supported."
                )
            value = stage["value"]["energy_hartree"]
        elif identity.observable == "equilibrium_rotational_constant":
            if stage["observable"] != "Be":
                raise ValueError(
                    "Stationary/nonminimum constants cannot be relabeled equilibrium."
                )
            value = stage["value"]["constants_mhz"]["ABC".index(identity.component)]
            if value is None:
                reason = "The chosen rotational axis is undefined for this rotor."
        else:
            raise ValueError(
                "This available observable has no validated benchmark scalar extractor."
            )
    prediction = {
        "bundle_path": str(root.absolute()),
        "identity": identity.model_dump(mode="json"),
        "value": value,
        "status": "available" if value is not None else "unavailable",
        "reason": reason,
        "publication_manifest_sha256": expected_manifest_sha256,
        "shard_manifest_sha256": manifest["shard_manifest_sha256"],
        "recipe_sha256": result["recipe_sha256"],
        "source_commit": result["source_identity"].get("git_commit"),
        "source_code_sha256": result["source_identity"]["code_sha256"],
        "benchmark_freeze_sha256": request.get("source_provenance", {}).get(
            "benchmark_freeze_sha256"
        ),
        "quality_flags": stage.get("quality_flags", []),
        "uncertainty": stage.get("uncertainty"),
        "reference_anchors": request.get("scientific_goal", {}).get("anchors", [])
        if request.get("scientific_goal")
        else [],
    }
    # The extractor reads request/result/summary after the initial inventory
    # verification. Verify the same independently trusted full inventory again
    # before returning, so a bundle changed during those reads cannot qualify.
    if (
        verify_publication_bundle(
            bundle, expected_manifest_sha256=expected_manifest_sha256
        )
        != manifest
    ):
        raise ValueError("Publication evidence changed during prediction extraction.")
    return prediction


def seal_predictions(
    frozen_path: str | Path,
    *,
    expected_freeze_sha256: str,
    bundles: Mapping[str, tuple[str | Path, str]],
    destination: str | Path,
) -> dict[str, Any]:
    """Seal actual bundle predictions before the scoring call opens references."""
    design, frozen_at = _read_frozen(frozen_path, expected_freeze_sha256)
    selected = {
        r.reference_id: r
        for r in design.selected_references
        if r.partition != "anchoring"
    }
    if set(bundles) != set(selected):
        raise ValueError(
            "Every selected non-anchor requires actual success/failure evidence."
        )
    predictions = []
    for reference_id, ref in selected.items():
        path, trusted_digest = bundles[reference_id]
        prediction = import_publication_prediction(
            path, expected_manifest_sha256=trusted_digest, identity=ref.identity
        )
        if prediction["recipe_sha256"] != design.recipe_sha256:
            raise ValueError("Prediction recipe differs from the frozen method.")
        if prediction["source_code_sha256"] != design.source_code_sha256 or (
            prediction["source_commit"] is not None
            and prediction["source_commit"] != design.source_commit
        ):
            raise ValueError("Prediction source commit differs from the frozen source.")
        if prediction["benchmark_freeze_sha256"] != expected_freeze_sha256:
            raise ValueError(
                "Original prediction request must bind the benchmark freeze."
            )
        if prediction["reference_anchors"] and ref.partition in {
            "calibration",
            "held_out",
        }:
            raise ValueError(
                "Experimentally anchored predictions cannot receive "
                "absolute independent scoring."
            )
        predictions.append({"reference_id": reference_id, **prediction})
    payload = {
        "schema_version": "cochem.torq.sealed-benchmark-predictions/1",
        "freeze_sha256": expected_freeze_sha256,
        "frozen_at": frozen_at.isoformat(),
        "sealed_at": datetime.now(timezone.utc).isoformat(),
        "predictions": predictions,
        "reference_values_opened_by_this_service": False,
        "experimental_accuracy_established": False,
    }
    seal_sha256 = _write_once(destination, payload)
    return {"prediction_seal_sha256": seal_sha256, "count": len(predictions)}


def grouped_split_conformal(
    group_scores: Mapping[str, float], *, nominal_coverage: float
) -> dict[str, Any]:
    """Exact order statistic on independent group maxima, without interpolation.

    This pure mathematical operation establishes no empirical exchangeability.
    With n calibration units the rank is ceil((n+1)*coverage); rank n+1
    requires an unbounded interval, represented as unavailable instead of a
    fabricated finite quantile. Repeated lines never increase n.
    """
    if (
        isinstance(nominal_coverage, bool)
        or not math.isfinite(nominal_coverage)
        or not 0 < nominal_coverage < 1
    ):
        raise ValueError("Nominal coverage must be finite and between zero and one.")
    if any(not isinstance(name, str) or not name.strip() for name in group_scores):
        raise ValueError("Independent sampling groups require explicit IDs.")
    if any(
        isinstance(score, bool)
        or not isinstance(score, (int, float))
        or not math.isfinite(score)
        or score < 0
        for score in group_scores.values()
    ):
        raise ValueError("Calibration scores must be finite, nonnegative real numbers.")
    count = len(group_scores)
    exact = (count + 1) * Fraction(str(nominal_coverage))
    rank = (exact.numerator + exact.denominator - 1) // exact.denominator
    finite = 1 <= rank <= count
    return {
        "calibration_group_count": count,
        "nominal_coverage": nominal_coverage,
        "order_statistic_rank": rank,
        "threshold": sorted(group_scores.values())[rank - 1] if finite else None,
        "status": "finite_mathematical_threshold"
        if finite
        else "unavailable_insufficient_independent_calibration_groups",
        "exchangeability_established": False,
        "coverage_claim": None,
    }


def _sampling_groups(selected: Sequence[SelectedReference]) -> dict[str, str]:
    """Connected families sharing source artifacts form one conservative unit."""
    parent = {ref.identity.family_id: ref.identity.family_id for ref in selected}

    def find(key: str) -> str:
        while parent[key] != key:
            key = parent[key]
        return key

    source_family: dict[str, str] = {}
    for ref in selected:
        family = ref.identity.family_id
        prior = source_family.setdefault(ref.source_sha256, family)
        a, b = find(prior), find(family)
        if a != b:
            parent[max(a, b)] = min(a, b)
    return {family: find(family) for family in parent}


def _metrics(rows: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    parents: dict[str, list[float]] = defaultdict(list)
    for row in rows:
        parents[row["parent_id"]].append(row["error"])
    if not rows:
        return {
            "parent_count": 0,
            "datum_count": 0,
            "parent_weighted_mae": None,
            "parent_weighted_rmse": None,
            "maximum_absolute_error": None,
        }
    return {
        "parent_count": len(parents),
        "datum_count": len(rows),
        "parent_weighted_mae": math.fsum(
            math.fsum(abs(e) for e in errors) / len(errors)
            for errors in parents.values()
        )
        / len(parents),
        "parent_weighted_rmse": math.sqrt(
            math.fsum(
                math.fsum(e * e for e in errors) / len(errors)
                for errors in parents.values()
            )
            / len(parents)
        ),
        "maximum_absolute_error": max(abs(row["error"]) for row in rows),
    }


def score_benchmark(
    frozen_path: str | Path,
    prediction_seal: str | Path,
    references: VerifiedReferences,
    *,
    expected_freeze_sha256: str,
    expected_prediction_seal_sha256: str,
    destination: str | Path,
) -> dict[str, Any]:
    """Score frozen, sealed evidence with missing cases in the denominator.

    Parent/family/source grouping avoids transition-count pseudo-replication.
    These diagnostics cannot independently qualify a method or its domain.
    """
    design, frozen_at = _read_frozen(frozen_path, expected_freeze_sha256)
    # Recheck actual supplied source and curator bytes, including when a caller
    # directly constructed the dataclass rather than using the import function.
    references = import_curated_references(
        references.manifest_bytes,
        dict(references.source_bytes),
        references.curation_bytes,
        expected_manifest_sha256=design.reference_manifest_sha256,
        expected_curation_sha256=design.curation_sha256,
    )
    if references.curation.reviewed_at > design.accepted_at:
        raise ValueError(
            "Accepted design must follow completion of its reference review."
        )
    seal_path = Path(prediction_seal).absolute()
    for component in (seal_path, *seal_path.parents):
        if component.is_symlink():
            raise ValueError("Prediction seals cannot traverse symlinks.")
    raw = seal_path.read_bytes()
    if sha256(raw).hexdigest() != expected_prediction_seal_sha256:
        raise ValueError("Prediction seal differs from independently retained digest.")
    seal = _decode(raw)
    if (
        seal.get("schema_version") != "cochem.torq.sealed-benchmark-predictions/1"
        or seal.get("freeze_sha256") != expected_freeze_sha256
    ):
        raise ValueError("Prediction seal belongs to another frozen benchmark.")
    sealed_at = _aware(datetime.fromisoformat(seal["sealed_at"]))
    if sealed_at < frozen_at or sealed_at > datetime.now(timezone.utc):
        raise ValueError("Predictions were sealed before the benchmark freeze.")
    if (
        references.manifest_sha256 != design.reference_manifest_sha256
        or references.curation_sha256 != design.curation_sha256
    ):
        raise ValueError("Scoring references differ from the frozen curated manifest.")
    datums = {r.reference_id: r for r in references.manifest.datums}
    selected = {r.reference_id: r for r in design.selected_references}
    for reference_id, ref in selected.items():
        datum = datums.get(reference_id)
        if (
            datum is None
            or datum.identity != ref.identity
            or datum.source_sha256 != ref.source_sha256
        ):
            raise ValueError(
                "Scoring reference identity differs from the frozen selection."
            )
    predictions = {p["reference_id"]: p for p in seal["predictions"]}
    expected_ids = {
        r.reference_id for r in design.selected_references if r.partition != "anchoring"
    }
    if len(predictions) != len(seal["predictions"]) or set(predictions) != expected_ids:
        raise ValueError(
            "Prediction seal has duplicate, missing or foreign references."
        )
    groups = _sampling_groups(design.selected_references)
    targets = {t.observable: t for t in design.targets}
    residuals: list[dict[str, Any]] = []
    missing: list[dict[str, Any]] = []
    anchors: list[str] = []
    scores: dict[str, dict[str, float]] = {"calibration": {}, "held_out": {}}
    for reference_id, ref in selected.items():
        if ref.partition == "anchoring":
            anchors.append(reference_id)
            continue
        prediction = predictions[reference_id]
        actual_prediction = import_publication_prediction(
            prediction["bundle_path"],
            expected_manifest_sha256=prediction["publication_manifest_sha256"],
            identity=ref.identity,
        )
        if prediction != {"reference_id": reference_id, **actual_prediction}:
            raise ValueError(
                "Prediction seal differs from actual verified bundle values."
            )
        if (
            prediction["identity"] != ref.identity.model_dump(mode="json")
            or prediction["recipe_sha256"] != design.recipe_sha256
            or prediction["source_code_sha256"] != design.source_code_sha256
            or (
                prediction["source_commit"] is not None
                and prediction["source_commit"] != design.source_commit
            )
            or prediction["benchmark_freeze_sha256"] != expected_freeze_sha256
        ):
            raise ValueError(
                "Sealed prediction violates its frozen identity/recipe/source."
            )
        value = prediction["value"]
        if value is None:
            missing.append(
                {
                    "reference_id": reference_id,
                    "partition": ref.partition,
                    "reason": prediction["reason"],
                }
            )
            continue
        if (
            isinstance(value, bool)
            or not isinstance(value, (float, int))
            or not math.isfinite(value)
        ):
            raise ValueError(
                "Predictions must remain finite actual scalar observations."
            )
        reference = datums[reference_id]
        error = value - reference.value
        if not math.isfinite(error):
            raise ValueError("Reference residual overflowed its finite scalar domain.")
        row: dict[str, Any] = {
            "reference_id": reference_id,
            "parent_id": ref.identity.parent_id,
            "family_id": ref.identity.family_id,
            "sampling_group": groups[ref.identity.family_id],
            "partition": ref.partition,
            "observable": ref.identity.observable,
            "unit": ref.identity.unit,
            "prediction": value,
            "reference": reference.value,
            "error": error,
            "relative_error_ppm": error / reference.value * 1e6
            if reference.value != 0
            else None,
            "standardized_residual": error / reference.standard_uncertainty
            if reference.standard_uncertainty is not None
            else None,
            "target_maximum_absolute_error": targets[
                ref.identity.observable
            ].maximum_absolute_error,
        }
        residuals.append(row)
        if ref.partition in scores:
            group = groups[ref.identity.family_id]
            normalized = (
                abs(error) / targets[ref.identity.observable].maximum_absolute_error
            )
            if not math.isfinite(normalized):
                raise ValueError("Normalized calibration residual overflowed.")
            scores[ref.partition][group] = max(
                scores[ref.partition].get(group, 0.0), normalized
            )
    incomplete_groups = {
        groups[selected[m["reference_id"]].identity.family_id] for m in missing
    }
    calibration = {
        g: s for g, s in scores["calibration"].items() if g not in incomplete_groups
    }
    conformal = grouped_split_conformal(
        calibration, nominal_coverage=design.nominal_coverage
    )
    held_out = {
        g: s for g, s in scores["held_out"].items() if g not in incomplete_groups
    }
    threshold = conformal["threshold"]
    observed = (
        math.fsum(s <= threshold for s in held_out.values()) / len(held_out)
        if threshold is not None and held_out
        else None
    )
    all_groups_complete = not missing
    supported = design.exchangeability_assessment == "externally_supported"
    # Even an external assessment does not turn this package into an independent
    # reviewer or a statistically justified empirical coverage certification.
    coverage = {
        **conformal,
        "exchangeability_assessment": design.exchangeability_assessment,
        "exchangeability_review": design.exchangeability_review,
        "held_out_group_count": len(held_out),
        "observed_simultaneous_group_coverage": observed,
        "status": conformal["status"]
        if threshold is None
        else "unavailable_missing_group_observations"
        if not all_groups_complete
        else "conditional_on_external_exchangeability_assessment"
        if supported
        else "descriptive_only_exchangeability_not_established",
        "coverage_claim": None,
        "confidence_interval": None,
        "reference_measurement_error_included": False,
    }
    metrics = {}
    for partition in ("development", "calibration", "held_out"):
        for observable in targets:
            subset = [
                r
                for r in residuals
                if r["partition"] == partition and r["observable"] == observable
            ]
            count = sum(
                r.partition == partition and r.identity.observable == observable
                for r in selected.values()
            )
            failures = sum(
                m["partition"] == partition
                and selected[m["reference_id"]].identity.observable == observable
                for m in missing
            )
            metrics[f"{partition}/{observable}"] = {
                **_metrics(subset),
                "unit": targets[observable].unit,
                "expected_datum_count": count,
                "missing_datum_count": failures,
                "failure_fraction": failures / count if count else None,
            }
    result = {
        "schema_version": "cochem.torq.benchmark-score/1",
        "benchmark_id": design.benchmark_id,
        "freeze_sha256": expected_freeze_sha256,
        "prediction_seal_sha256": expected_prediction_seal_sha256,
        "reference_manifest_sha256": references.manifest_sha256,
        "curation_sha256": references.curation_sha256,
        "scored_at": datetime.now(timezone.utc).isoformat(),
        "residuals": residuals,
        "missing": missing,
        "anchors_excluded": anchors,
        "metrics": metrics,
        "calibration": coverage,
        "observed_targets_met": not missing
        and all(
            abs(r["error"]) <= r["target_maximum_absolute_error"]
            for r in residuals
            if r["partition"] == "held_out"
        ),
        "experimental_accuracy_established": False,
        "identification_ready": False,
        "limitations": [
            "Reference authorship and scientific authenticity "
            "require external curation.",
            "Family/source group exchangeability is an external scientific assumption.",
            "Nominal conformal coverage concerns recorded reference values, "
            "not latent error-free quantities.",
            "No covariance-aware difference or intensity likelihood is inferred.",
            "Observed target comparisons cannot independently qualify "
            "a method or deployment.",
        ],
    }
    result_sha256 = _write_once(destination, result)
    return {"score_sha256": result_sha256, "result": result}
