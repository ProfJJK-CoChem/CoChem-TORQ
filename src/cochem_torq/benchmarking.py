"""Frozen, source-bound benchmarks and conservative grouped error diagnostics.

Hashes authenticate retained bytes against externally trusted digests, not an
author, experiment, permission or scientific claim. Reference curation remains
an explicit external review. No references, target values or observations are
generated by this module. Mathematical calibration never activates a recipe.
"""

