def _nonzero_digest(value: str) -> str:
    if value == "0" * 64:
        raise ValueError("A zero digest cannot identify authentic retained bytes.")
    return value


Sha256 = Annotated[
    str, Field(pattern=r"^[0-9a-f]{64}$"), AfterValidator(_nonzero_digest)
]
Partition = Literal["development", "calibration", "held_out", "anchoring"]
Observable = Literal[
    "electronic_energy",
    "equilibrium_rotational_constant",
    "ground_state_rotational_constant",
    "rotational_transition",
    "relative_line_intensity",
]


def _aware(value: datetime) -> datetime:
    if value.utcoffset() is None:
        raise ValueError("An aware timestamp is required.")
    return value


def _decode(raw: bytes) -> Any:
    def unique(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, value in pairs:
            if key in result:
                raise ValueError("Duplicate JSON object members are forbidden.")
            result[key] = value
        return result

    return json.loads(raw, object_pairs_hook=unique)


class ObservableIdentity(ScientificContract):
    parent_id: Name
    family_id: Name
    symbols: tuple[Name, ...] = Field(min_length=1)
    isotope_numbers: tuple[StrictInt, ...] = Field(min_length=1)
    charge: StrictInt
    multiplicity: StrictInt = Field(ge=1)
    conformer: Name
    electronic_state: Name
    vibrational_state: Name
    tunneling_state: Name
    hamiltonian_convention: Name
    observable: Observable
    component: Name
    unit: Unit

    @model_validator(mode="after")
    def physical_identity(self) -> Self:
        if (
            len(self.symbols) != len(self.isotope_numbers)
            or any(symbol not in ATOMIC_NUMBERS for symbol in self.symbols)
            or any(number < 1 or number > 350 for number in self.isotope_numbers)
        ):
            raise ValueError("Every canonical atom requires its explicit isotope.")
        electrons = sum(ATOMIC_NUMBERS[s] for s in self.symbols) - self.charge
        spin = self.multiplicity - 1
        if electrons < 1 or spin > electrons or (electrons - spin) % 2:
            raise ValueError("Charge and multiplicity disagree with electron count.")
        required_unit = {
            "electronic_energy": "hartree",
            "equilibrium_rotational_constant": "MHz",
            "ground_state_rotational_constant": "MHz",
            "rotational_transition": "MHz",
            "relative_line_intensity": "dimensionless",
        }[self.observable]
        if self.unit != required_unit:
            raise ValueError("Use the exact declared benchmark observable unit.")
        if self.observable.endswith("rotational_constant") and self.component not in {
            "A",
            "B",
            "C",
        }:
            raise ValueError("A rotational constant requires its A/B/C component.")
        return self


class ReferenceArtifact(ScientificContract):
    source_sha256: Sha256
    citation: Name
    persistent_identifier: Name
    version: Name
    retrieved_at: datetime
    reuse_permission: Name
    origin: Literal[
        "measured", "experimentally_fitted", "semi_experimental", "catalogue_prediction"
    ]

    @model_validator(mode="after")
    def provenance(self) -> Self:
        _aware(self.retrieved_at)
        if not self.persistent_identifier.startswith(("doi:", "https://")):
            raise ValueError("An explicit DOI or HTTPS source locator is required.")
        return self


class ReferenceDatum(ScientificContract):
    reference_id: Name
    identity: ObservableIdentity
    value: StrictFloat
    standard_uncertainty: StrictFloat | None = Field(default=None, gt=0)
    uncertainty_status: Literal["standard_uncertainty", "unavailable"]
    covariance_status: Literal["unavailable", "not_applicable"]
    source_sha256: Sha256
    datum_locator: Name
    correction_sources: tuple[Name, ...] = ()

    @model_validator(mode="after")
    def uncertainty_and_sign(self) -> Self:
        if (self.uncertainty_status == "standard_uncertainty") != (
            self.standard_uncertainty is not None
        ):
            raise ValueError("Unavailable uncertainty must remain absent.")
        if self.identity.observable != "electronic_energy" and self.value <= 0:
            raise ValueError("This observable requires a positive reference value.")
        return self


class ReferenceManifest(ScientificContract):
    schema_version: Literal["cochem.torq.curated-benchmark-references/1"] = (
        "cochem.torq.curated-benchmark-references/1"
    )
    sources: tuple[ReferenceArtifact, ...] = Field(min_length=1)
    datums: tuple[ReferenceDatum, ...] = Field(min_length=1)

    @model_validator(mode="after")
    def complete_inventory(self) -> Self:
        sources = {source.source_sha256: source for source in self.sources}
        if len(sources) != len(self.sources) or len(
            {datum.reference_id for datum in self.datums}
        ) != len(self.datums):
            raise ValueError("Source digests and reference IDs must be unique.")
        for datum in self.datums:
            if datum.source_sha256 not in sources:
                raise ValueError("Each datum requires an actual inventoried source.")
            source = sources[datum.source_sha256]
            if source.origin == "catalogue_prediction":
                raise ValueError(
                    "Catalogue predictions are not independent observations."
                )
            if datum.identity.observable == "equilibrium_rotational_constant" and (
                source.origin != "semi_experimental" or not datum.correction_sources
            ):
                raise ValueError(
                    "Equilibrium references require independent correction provenance; "
                    "ground-state fits cannot be relabeled equilibrium constants."
                )
        if set(sources) != {datum.source_sha256 for datum in self.datums}:
            raise ValueError(
                "Reference inventory cannot include unbound source artifacts."
            )
        return self


class CurationAttestation(ScientificContract):
    schema_version: Literal["cochem.torq.reference-curation-attestation/1"] = (
        "cochem.torq.reference-curation-attestation/1"
    )
    reference_manifest_sha256: Sha256
    curator: Name
    reviewed_at: datetime
    identity_units_extraction_and_origin_reviewed: Literal[True]
    reuse_permission_reviewed: Literal[True]
    independence_reviewed: Literal[True]
    review_record: Name

    @model_validator(mode="after")
    def aware(self) -> Self:
        _aware(self.reviewed_at)
        return self


@dataclass(frozen=True)
class VerifiedReferences:
    manifest: ReferenceManifest
    manifest_sha256: str
    curation: CurationAttestation
    curation_sha256: str
    # These immutable byte objects preserve evidence supplied by the caller.
    source_bytes: tuple[tuple[str, bytes], ...]
    manifest_bytes: bytes
    curation_bytes: bytes


def import_curated_references(
    manifest_bytes: bytes,
    source_artifacts: Mapping[str, bytes],
    curation_bytes: bytes,
    *,
    expected_manifest_sha256: str,
    expected_curation_sha256: str,
) -> VerifiedReferences:
    """Verify retained bytes and externally attested curation, not authorship.

    Trusted digests must come from the curator's independent review channel.
    Creating a self-consistent digest is never experimental authentication.
    """
    if (
        sha256(manifest_bytes).hexdigest() != expected_manifest_sha256
        or sha256(curation_bytes).hexdigest() != expected_curation_sha256
    ):
        raise ValueError(
            "Reference/curation bytes differ from independently retained digests."
        )
    manifest = ReferenceManifest.model_validate(_decode(manifest_bytes))
    curation = CurationAttestation.model_validate(_decode(curation_bytes))
    if curation.reference_manifest_sha256 != expected_manifest_sha256:
        raise ValueError("Curation attestation belongs to another reference manifest.")
    if set(source_artifacts) != {s.source_sha256 for s in manifest.sources}:
        raise ValueError("All and only inventoried raw source artifacts are required.")
    for expected, raw in source_artifacts.items():
        if not isinstance(raw, bytes) or sha256(raw).hexdigest() != expected:
            raise ValueError("Raw reference source artifact digest mismatch.")
    if any(source.retrieved_at > curation.reviewed_at for source in manifest.sources):
        raise ValueError("A curator cannot review a source before its retrieval.")
    if curation.reviewed_at > datetime.now(timezone.utc):
        raise ValueError("A future curator review is not completed reference evidence.")
    return VerifiedReferences(
        manifest,
        expected_manifest_sha256,
        curation,
        expected_curation_sha256,
        tuple(sorted(source_artifacts.items())),
        manifest_bytes,
        curation_bytes,
    )


